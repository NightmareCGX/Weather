"""System resource monitoring and cycle-to-cycle resource leak detection.

Exposes low-overhead, bounded process and host metrics (CPU, RSS, VMS, threads,
asyncio tasks, file descriptors, GC stats, disk capacity) with cross-platform
support for Windows and Linux. Tracks resource baselines across ingestion cycles
to detect sustained monotonic memory leaks without false alarms on temporary peaks.
"""

from __future__ import annotations

import asyncio
import ctypes
import gc
import logging
import shutil
import sys
import threading
import time
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from ingestion.monitoring.metrics import REGISTRY

logger = logging.getLogger(__name__)

