def select_gfs_records(
    records: list[IdxRecord],
    lead_time_hours: int,
    variables: tuple[str, ...] = DEFAULT_SELECTION_VARIABLES,
) -> SelectionResult:
    """Select required GFS GRIB2 records from parsed .idx records.

    GFS Operational Rules:
    * ``temperature_2m``: Matches parameter ``"TMP"`` at level
      ``"2 m above ground"``. At lead 0, matches ``"anl"`` or ``"0 hour fcst"``;
      at lead > 0, matches ``f"{lead_time_hours} hour fcst"``.
    * ``precipitation_rate``: Matches parameter ``"PRATE"`` at level
      ``"surface"``. Strictly matches instantaneous forecast description
      (e.g. ``f"{lead_time_hours} hour fcst"`` or ``"0 hour fcst"`` / ``"anl"``),
      and explicitly rejects time-averaged variants (``"ave fcst"``) or
      accumulated variants (``"acc fcst"``).
    * ``relative_humidity_2m``: Matches parameter ``"RH"`` at level
      ``"2 m above ground"``. At lead 0, matches ``"anl"`` or ``"0 hour fcst"``;
      at lead > 0, matches ``f"{lead_time_hours} hour fcst"``.
    * ``wind_gust``: Matches parameter ``"GUST"`` at level ``"surface"``.
      At lead 0, matches ``"anl"`` or ``"0 hour fcst"``; at lead > 0, matches
      ``f"{lead_time_hours} hour fcst"``.
    * ``visibility``: Matches parameter ``"VIS"`` at level ``"surface"``.
      At lead 0, matches ``"anl"`` or ``"0 hour fcst"``; at lead > 0, matches
      ``f"{lead_time_hours} hour fcst"``.
    * ``snow_depth``: Matches parameter ``"SNOD"`` at level ``"surface"``.
      At lead 0, matches ``"anl"`` or ``"0 hour fcst"``; at lead > 0, matches
      ``f"{lead_time_hours} hour fcst"``.
    * ``wind_u_10m``: Matches parameter ``"UGRD"`` at level
      ``"10 m above ground"``. At lead 0, matches ``"anl"`` or ``"0 hour fcst"``;
      at lead > 0, matches ``f"{lead_time_hours} hour fcst"``.
    * ``wind_v_10m``: Matches parameter ``"VGRD"`` at level
      ``"10 m above ground"``. At lead 0, matches ``"anl"`` or ``"0 hour fcst"``;
      at lead > 0, matches ``f"{lead_time_hours} hour fcst"``.

    Args:
        records: Parsed ``.idx`` records.
        lead_time_hours: Target forecast lead time.
        variables: Canonical platform variable codes to select.

    Returns:
        A :class:`SelectionResult` detailing selected records and any anomalies.
    """
    variable_selections: dict[str, VariableSelection] = {}
    missing_required: list[str] = []
    unsupported: list[str] = []
    ambiguous: list[str] = []
    all_selected: list[IdxRecord] = []

    for var in variables:
        if var == "temperature_2m":
            matches = [
                rec
                for rec in records
                if rec.parameter == "TMP"
                and rec.level_description == "2 m above ground"
                and _matches_step(rec.forecast_description, lead_time_hours)
            ]
            _record_selection(
                var,
                matches,
                variable_selections,
                all_selected,
                missing_required,
                ambiguous,
            )

        elif var == "precipitation_rate":
            matches = [
                rec
                for rec in records
                if rec.parameter == "PRATE"
                and rec.level_description == "surface"
                and _matches_step(rec.forecast_description, lead_time_hours)
                and "ave fcst" not in rec.forecast_description
                and "acc fcst" not in rec.forecast_description
            ]
            _record_selection(
                var,
                matches,
                variable_selections,
                all_selected,
                missing_required,
                ambiguous,
            )

        elif var == "relative_humidity_2m":
            matches = [
                rec
                for rec in records
                if rec.parameter == "RH"
                and rec.level_description == "2 m above ground"
                and _matches_step(rec.forecast_description, lead_time_hours)
            ]
            _record_selection(
                var,
                matches,
                variable_selections,
                all_selected,
                missing_required,
                ambiguous,
            )

        elif var == "wind_gust":
            matches = [
                rec
                for rec in records
                if rec.parameter == "GUST"
                and rec.level_description == "surface"
                and _matches_step(rec.forecast_description, lead_time_hours)
            ]
            _record_selection(
                var,
                matches,
                variable_selections,
                all_selected,
                missing_required,
                ambiguous,
            )

        elif var == "visibility":
            matches = [
                rec
                for rec in records
                if rec.parameter == "VIS"
                and rec.level_description == "surface"
                and _matches_step(rec.forecast_description, lead_time_hours)
            ]
            _record_selection(
                var,
                matches,
                variable_selections,
                all_selected,
                missing_required,
                ambiguous,
            )

        elif var == "snow_depth":
            matches = [
                rec
                for rec in records
                if rec.parameter == "SNOD"
                and rec.level_description == "surface"
                and _matches_step(rec.forecast_description, lead_time_hours)
            ]
            _record_selection(
                var,
                matches,
                variable_selections,
                all_selected,
                missing_required,
                ambiguous,
            )

        elif var == "wind_u_10m":
            matches = [
                rec
                for rec in records
                if rec.parameter == "UGRD"
                and rec.level_description == "10 m above ground"
                and _matches_step(rec.forecast_description, lead_time_hours)
            ]
            _record_selection(
                var,
                matches,
                variable_selections,
                all_selected,
                missing_required,
                ambiguous,
            )

        elif var == "wind_v_10m":
            matches = [
                rec
                for rec in records
                if rec.parameter == "VGRD"
                and rec.level_description == "10 m above ground"
                and _matches_step(rec.forecast_description, lead_time_hours)
            ]
            _record_selection(
                var,
                matches,
                variable_selections,
                all_selected,
                missing_required,
                ambiguous,
            )

        elif var == "precipitation_amount_3h":
            if lead_time_hours == 0:
                # Analysis time has zero accumulation duration; no GRIB record required
                variable_selections[var] = VariableSelection(
                    variable_code=var,
                    status=SelectionStatus.SELECTED,
                    record=None,
                )
            else:
                expected_desc = _expected_apcp_description(lead_time_hours)
                if expected_desc is None:
                    variable_selections[var] = VariableSelection(
                        variable_code=var,
                        status=SelectionStatus.UNSUPPORTED,
                    )
                    unsupported.append(var)
                else:
                    matches = [
                        rec
                        for rec in records
                        if rec.parameter == "APCP"
                        and rec.level_description == "surface"
                        and rec.forecast_description.strip().lower() == expected_desc
                    ]
                    # If multiple identical matches exist (e.g. GFS f003/f006 duplicate lines),
                    # pick the first one (the 6h-resetting family).
                    if len(matches) > 1:
                        matches = [matches[0]]
                    _record_selection(
                        var,
                        matches,
                        variable_selections,
                        all_selected,
                        missing_required,
                        ambiguous,
                    )

        elif var in ("crain", "csnow", "cfrzr", "cicep"):
            if lead_time_hours == 0:
                # Analysis time has no interval-average categorical flags
                variable_selections[var] = VariableSelection(
                    variable_code=var,
                    status=SelectionStatus.SELECTED,
                    record=None,
                )
            else:
                expected_desc = _expected_categorical_description(lead_time_hours)
                param_name = var.upper()
                if expected_desc is None:
                    variable_selections[var] = VariableSelection(
                        variable_code=var,
                        status=SelectionStatus.UNSUPPORTED,
                    )
                    unsupported.append(var)
                else:
                    matches = [
                        rec
                        for rec in records
                        if rec.parameter == param_name
                        and rec.level_description == "surface"
                        and rec.forecast_description.strip().lower() == expected_desc
                    ]
                    if len(matches) > 1:
                        matches = [matches[0]]
                    _record_selection(
                        var,
                        matches,
                        variable_selections,
                        all_selected,
                        missing_required,
                        ambiguous,
                    )

        elif var == "cloud_cover_3h":
            if lead_time_hours == 0:
                # Analysis time has no interval-average cloud cover record
                variable_selections[var] = VariableSelection(
                    variable_code=var,
                    status=SelectionStatus.SELECTED,
                    record=None,
                )
            else:
                expected_desc = _expected_categorical_description(lead_time_hours)
                if expected_desc is None:
                    variable_selections[var] = VariableSelection(
                        variable_code=var,
                        status=SelectionStatus.UNSUPPORTED,
                    )
                    unsupported.append(var)
                else:
                    matches = [
                        rec
                        for rec in records
                        if rec.parameter == "TCDC"
                        and rec.level_description == "entire atmosphere"
                        and rec.forecast_description.strip().lower() == expected_desc
                    ]
                    if len(matches) > 1:
                        matches = [matches[0]]
                    _record_selection(
                        var,
                        matches,
                        variable_selections,
                        all_selected,
                        missing_required,
                        ambiguous,
                    )

        elif var == "cloud_ceiling":
            matches = [
                rec
                for rec in records
                if rec.parameter == "HGT"
                and rec.level_description == "cloud ceiling"
                and _matches_step(rec.forecast_description, lead_time_hours)
            ]
            _record_selection(
                var,
                matches,
                variable_selections,
                all_selected,
                missing_required,
                ambiguous,
            )

        else:
            variable_selections[var] = VariableSelection(
                variable_code=var,
                status=SelectionStatus.UNSUPPORTED,
            )
            unsupported.append(var)

    # Sort selected records strictly by byte offset to preserve upstream GRIB order
    sorted_selected = tuple(sorted(all_selected, key=lambda r: r.start_offset))

    return SelectionResult(
        selected_records=sorted_selected,
        variable_selections=variable_selections,
        missing_required=tuple(missing_required),
        unsupported=tuple(unsupported),
        ambiguous=tuple(ambiguous),
    )


def merge_adjacent_records(
    records: tuple[IdxRecord, ...] | list[IdxRecord],
    *,
    max_gap: int = 0,
) -> tuple[tuple[IdxRecord, ...], ...]:
    """Group sorted IdxRecords into contiguous or near-contiguous spans.

    Two consecutive records r1 and r2 are grouped together if:
    ``r2.start_offset - (r1.end_offset + 1) <= max_gap`` (where r1.end_offset is not None).

    When ``max_gap == 0`` (default), strictly groups only physically adjacent records
    (0-byte gap) with zero extra byte overhead.

    Args:
        records: Sequence of IdxRecord instances, sorted by start_offset.
        max_gap: Maximum allowed gap in bytes between consecutive records to merge.

    Returns:
        A tuple of record groups (each group is a tuple of IdxRecord).
    """
    if not records:
        return ()

    groups: list[list[IdxRecord]] = []
    cur_group: list[IdxRecord] = [records[0]]

    for r in records[1:]:
        prev = cur_group[-1]
        gap = (
            r.start_offset - (prev.end_offset + 1)
            if prev.end_offset is not None
            else 999999999999
        )
        if gap <= max_gap:
            cur_group.append(r)
        else:
            groups.append(cur_group)
            cur_group = [r]

    if cur_group:
        groups.append(cur_group)

    return tuple(tuple(g) for g in groups)


def _record_selection(
    var: str,
    matches: list[IdxRecord],
    variable_selections: dict[str, VariableSelection],
    all_selected: list[IdxRecord],
    missing_required: list[str],
    ambiguous: list[str],
) -> None:
    """Helper to record matches into variable selection and error buckets."""
    if len(matches) == 1:
        rec = matches[0]
        variable_selections[var] = VariableSelection(
            variable_code=var,
            status=SelectionStatus.SELECTED,
            record=rec,
            matched_records=tuple(matches),
        )
        all_selected.append(rec)
    elif len(matches) == 0:
        variable_selections[var] = VariableSelection(
            variable_code=var,
            status=SelectionStatus.REQUIRED_BUT_MISSING,
        )
        missing_required.append(var)
    else:
        variable_selections[var] = VariableSelection(
            variable_code=var,
            status=SelectionStatus.AMBIGUOUS,
            matched_records=tuple(matches),
        )
        ambiguous.append(var)


