"""Strict parser and product-aware record selector for NOAA NOMADS .idx files.

NOMADS serves a ``.idx`` file alongside every operational GFS and GEFS GRIB2
product. These index files are generated by ``wgrib2`` with standard 1-based
message lines:

    <record_num>:<byte_offset>:d=<cycle>:<parameter>:<level>:<forecast_step>[:<extra>]

This module provides:
1. :class:`IdxRecord` — an immutable representation of one GRIB2 record boundary
   and its descriptive metadata.
2. :func:`parse_idx` — a strict parser enforcing sequential record numbers,
   monotonically increasing byte offsets, and non-empty metadata.
3. :func:`select_records` — product-aware record selection that resolves
   platform-required variables (e.g. ``temperature_2m``, ``precipitation_rate``)
   to exact GRIB message byte boundaries for GFS and GEFS.
"""

from __future__ import annotations

from dataclasses import dataclass
from enum import Enum

from ingestion.core.base import IngestionError


class IdxParseError(IngestionError):
    """Raised when a NOMADS .idx file cannot be parsed or violates invariants."""


class SelectionStatus(str, Enum):
    """Classification of a variable selection outcome."""

    SELECTED = "selected"
    UNSUPPORTED = "unsupported"
    REQUIRED_BUT_MISSING = "required_but_missing"
    AMBIGUOUS = "ambiguous"


@dataclass(frozen=True, slots=True)
class IdxRecord:
    """An immutable description of a single GRIB2 message within a remote file.

    Attributes:
        record_number: 1-based sequence index in the GRIB2 file.
        start_offset: Absolute start byte offset in the remote GRIB2 file.
        end_offset: Inclusive end byte offset, or ``None`` for the final record
            when the total file size is not yet bounded.
        date_token: Reference cycle token (e.g. ``"d=2026082600"``).
        parameter: GRIB parameter mnemonic (e.g. ``"TMP"``, ``"PRATE"``).
        level_description: Vertical level string (e.g. ``"2 m above ground"``).
        forecast_description: Forecast step/type string (e.g. ``"6 hour fcst"``).
        ensemble_description: Optional ensemble metadata (e.g. ``"ENS=+1"``).
        raw_line: The exact original line from the ``.idx`` stream.
    """

    record_number: int
    start_offset: int
    end_offset: int | None
    date_token: str
    parameter: str
    level_description: str
    forecast_description: str
    ensemble_description: str
    raw_line: str

    @property
    def byte_length(self) -> int | None:
        """Return the exact byte span, or ``None`` if unbounded."""
        if self.end_offset is None:
            return None
        return self.end_offset - self.start_offset + 1


@dataclass(frozen=True)
class VariableSelection:
    """Selection outcome for a single canonical platform variable."""

    variable_code: str
    status: SelectionStatus
    record: IdxRecord | None = None
    matched_records: tuple[IdxRecord, ...] = ()


@dataclass(frozen=True)
class SelectionResult:
    """Aggregated selection outcome for all requested variables.

    Attributes:
        selected_records: Records to download, strictly sorted by ``start_offset``
            ascending to preserve original upstream GRIB message order.
        variable_selections: Map of variable code to its selection outcome.
        missing_required: List of required variables that were unexpectedly missing.
        unsupported: List of variables not supported by this product layout.
        ambiguous: List of variables that matched multiple conflicting records.
    """

    selected_records: tuple[IdxRecord, ...]
    variable_selections: dict[str, VariableSelection]
    missing_required: tuple[str, ...]
    unsupported: tuple[str, ...]
    ambiguous: tuple[str, ...]

    @property
    def is_valid(self) -> bool:
        """Return True if all required variables were unambiguously resolved."""
        return len(self.missing_required) == 0 and len(self.ambiguous) == 0


def parse_idx(text: str) -> list[IdxRecord]:
    r"""Parse raw NOMADS .idx text into a strictly validated list of IdxRecords.

    Enforces:
    * Non-empty text.
    * Each line has at least 6 colon-separated fields.
    * Record numbers are strictly sequential ($1, 2, 3, \dots, N$).
    * Byte offsets are non-negative, starting at 0, and strictly monotonically
      increasing without duplicates.
    * End offsets are derived as ``start_offset[i+1] - 1`` (and ``None`` for
      the final record).

    Args:
        text: Raw UTF-8 text of a NOMADS ``.idx`` file.

    Returns:
        List of parsed :class:`IdxRecord` instances.

    Raises:
        IdxParseError: If the index is empty, malformed, or violates offset
            monotonicity.
    """
    stripped = text.strip()
    if not stripped:
        raise IdxParseError("Empty or whitespace-only .idx content")

    lines = [line.strip() for line in stripped.splitlines() if line.strip()]
    if not lines:
        raise IdxParseError("No valid record lines found in .idx")

    raw_records: list[tuple[int, int, str, str, str, str, str, str]] = []
    prev_offset = -1

    for idx, line in enumerate(lines):
        parts = line.split(":")
        if len(parts) < 6:
            raise IdxParseError(
                f"Malformed .idx line {idx + 1}: expected at least 6 fields, "
                f"got {len(parts)}: {line!r}"
            )

        try:
            rec_num = int(parts[0])
        except ValueError as exc:
            raise IdxParseError(
                f"Invalid record number on line {idx + 1}: {parts[0]!r}"
            ) from exc

        expected_rec_num = idx + 1
        if rec_num != expected_rec_num:
            raise IdxParseError(
                f"Non-sequential record number on line {idx + 1}: "
                f"expected {expected_rec_num}, got {rec_num}"
            )

        try:
            start_offset = int(parts[1])
        except ValueError as exc:
            raise IdxParseError(
                f"Invalid byte offset on line {idx + 1}: {parts[1]!r}"
            ) from exc

        if start_offset < 0:
            raise IdxParseError(
                f"Negative byte offset on line {idx + 1}: {start_offset}"
            )

        if idx == 0 and start_offset != 0:
            raise IdxParseError(
                f"First record on line 1 must start at byte offset 0, got {start_offset}"
            )

        if idx > 0 and start_offset <= prev_offset:
            raise IdxParseError(
                f"Non-increasing byte offset on line {idx + 1}: {start_offset} "
                f"<= previous offset {prev_offset}"
            )

        date_token = parts[2].strip()
        parameter = parts[3].strip()
        level_desc = parts[4].strip()
        forecast_desc = parts[5].strip()
        extra = ":".join(parts[6:]).strip() if len(parts) > 6 else ""

        raw_records.append(
            (
                rec_num,
                start_offset,
                date_token,
                parameter,
                level_desc,
                forecast_desc,
                extra,
                line,
            )
        )
        prev_offset = start_offset

    total_records = len(raw_records)
    records: list[IdxRecord] = []

    for i, (rec_num, start_off, date_tok, param, lvl, fcst, ext, raw) in enumerate(
        raw_records
    ):
        if i + 1 < total_records:
            next_start = raw_records[i + 1][1]
            end_off: int | None = next_start - 1
        else:
            end_off = None

        records.append(
            IdxRecord(
                record_number=rec_num,
                start_offset=start_off,
                end_offset=end_off,
                date_token=date_tok,
                parameter=param,
                level_description=lvl,
                forecast_description=fcst,
                ensemble_description=ext,
                raw_line=raw,
            )
        )

    return records


